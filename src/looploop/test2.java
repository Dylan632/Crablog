package looploop;

public class test2 {
    public static void main(String[] args) {
        /*
        打印3行4列*
         */
        for (int i = 0; i < 3; i++) {
            for (int j = 0; j < 4; j++) {
                System.out.print("*");
            }
            System.out.println();
        }
    }
}
